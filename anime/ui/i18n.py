def tr(message):
    """Translate a Portuguese UI string according to the saved language."""
    message = str(message)
    if settings.language() == 'pt':
        return message
    translated = _PT_TO_EN.get(message)
    if translated is not None:
        return translated
    for pattern, replacement in _PT_PATTERNS:
        match = pattern.fullmatch(message)
        if match:
            try:
                return replacement.format(*match.groups())
            except (IndexError, ValueError):
                break
    return message
